# -*- coding: utf-8 -*-
"""知识点名称归一化（v0.4.16）

LLM 返回的 knowledge_point 是自由文本，同一知识点常出现多种写法：
- 空格/全角空格："两位数乘 法"、"两位数乘法"
- 全角/半角标点与字母数字："100以内加法" vs "１００以内加法"、"乘、法" 
- 常见别名："两位数乘法" ≈ "二位数乘法"，"进位加法" ≈ "进位加"
聚合统计前必须先归一化，否则学情看板的同一知识点被拆成多条，正确率失真。

策略（保守优先，拿不准不改写）：
1. 规范化层：去空白（含全角空格）、全角→半角（字母数字标点）、去末尾标点、
   统一常见分隔符，叠词去重不做（误伤风险高）。
2. 别名层：小规模精确映射表（key 为规范化后的写法），只收高置信同义对。
3. 相似度层不做：小学知识点名称短，编辑距离易误合（"进位加法"vs"退位减法"距离近但完全不同）。
"""
import re

# 全角 → 半角映射（字母、数字、常用标点、空格）
_FW = "０１２３４５６７８９ＡＺＢＸＣＶＢＮＭＱＷＥＲＴＹＵＩＯＰＬＫＪＨＧＦＤＳ，．；：？！（）「」『』　"
_HB = "0123456789AZBXCVBNMQWERTYUIOPLKJHGFD S"
_FW_TABLE = {ord(f): h for f, h in zip(_FW, _HB) if h != " "}
_FW_TABLE[0x3000] = " "  # 全角空格

# 别名表：规范化后的写法 → 标准名（只收高置信同义对，后续按真实数据扩充）
_ALIASES = {
    "二位数乘法": "两位数乘法",
    "二位数加法": "两位数加法",
    "二位数减法": "两位数减法",
    "进位加": "进位加法",
    "退位减": "退位减法",
    "乘法竖式": "竖式乘法",
    "加法竖式": "竖式加法",
    "减法竖式": "竖式减法",
}

_TRAIL_PUNCT = "。，、；：!?,;:.·-—_ "


def normalize_knowledge_point(name) -> str:
    """归一化知识点名称：去空白、全角→半角、去首尾标点、别名映射。"""
    if not name:
        return ""
    s = str(name).translate(_FW_TABLE)
    s = re.sub(r"\s+", "", s)          # 所有空白（含全角）直接删除：中文名内不应有空白
    s = s.strip(_TRAIL_PUNCT)
    if not s:
        return ""
    return _ALIASES.get(s, s)


def canonical_key(name) -> str:
    """聚合用 key：小写统一（防英文大小写差异），归一化后仍空则返回空串。"""
    s = normalize_knowledge_point(name)
    return s.lower() if s else ""
